import { setup, sleep } from "./lib.mjs";
const c = await setup();
await c.ev2(`app.hotkeyManager.setHotkeys("editor:toggle-bold",[{modifiers:["Alt"],key:"N"}]); await app.hotkeyManager.save(); return 1`);
await c.ev2(`return await E.open("tab", "abc")`);
await c.ev2(`E.editor.setSelection({line:0,ch:0},{line:0,ch:3}); return 1`);
await c.key("n", { alt: true }); await sleep(800);
console.log("text:", await c.ev2("return E.text()"), "modal:", await c.ev2(`return !!document.querySelector(".modal-container .prompt")`));
await c.key("Escape");
await c.ev2(`app.hotkeyManager.removeHotkeys("editor:toggle-bold"); await app.hotkeyManager.save(); return 1`);
process.exit(0);
